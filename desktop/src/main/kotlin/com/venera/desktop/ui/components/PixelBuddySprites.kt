    fun DrawScope.drawPixelMatrix(
        rows: List<String>,
        palette: PixelPalette,
        centerX: Float,
        centerY: Float,
        cellPx: Float,
        rotationDeg: Float = 0f,
        flipX: Boolean = false,
        scaleX: Float = 1f,
        scaleY: Float = 1f,
    ) {
        if (rows.isEmpty()) return
        val w = rows[0].length * cellPx
        val h = rows.size * cellPx
        withTransform({
            translate(left = centerX, top = centerY)
            if (rotationDeg != 0f) rotate(degrees = rotationDeg, pivot = Offset.Zero)
            val sx = if (flipX) -scaleX else scaleX
            if (sx != 1f || scaleY != 1f) scale(scaleX = sx, scaleY = scaleY, pivot = Offset.Zero)
        }) {
            val ox = -w / 2f
            val oy = -h / 2f
            for (ry in rows.indices) {
                val line = rows[ry]
                var rx = 0
                while (rx < line.length) {
                    val ch = line[rx]
                    var run = 1
                    while (rx + run < line.length && line[rx + run] == ch) run++
                    val color = when (ch) {
                        '#' -> palette.body
                        's' -> palette.shadow
                        'o' -> palette.eye
                        'r' -> palette.red
                        'a' -> palette.accent
                        'y' -> palette.yellow
                        'w' -> palette.white
                        'b' -> palette.brown
                        else -> null
                    }
                    if (color != null) {
                        drawRect(
                            color = color,
                            topLeft = Offset(ox + rx * cellPx, oy + ry * cellPx),
                            size = Size(run * cellPx, cellPx),
                        )
                    }
                    rx += run
                }
            }
        }
    }
